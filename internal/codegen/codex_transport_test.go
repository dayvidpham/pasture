// TestCodexLifecycleTransportIsPythonFree walks the committed lifecycle
// transport tree (.codex/hooks and .codex/hooks.json) and proves it carries no
// Python file, no python3 invocation, no reference to the deleted adapter, and
// no caller-selected PASTURE_ADAPTER_* operation env — the hard #65 invariant.
// Expected to FAIL until L3 deletes .codex/hooks/pasture-lifecycle.py and
// regenerates the runners.
func TestCodexLifecycleTransportIsPythonFree(t *testing.T) {
	t.Parallel()
	root := testModuleRoot(t)
	transport := filepath.Join(root, filepath.FromSlash(codexLifecycleTransportRoot))

	forbiddenTokens := []string{
		"python", "python3", "pasture-lifecycle.py",
		"PASTURE_ADAPTER_EVENT", "PASTURE_ADAPTER_OPERATION", "PASTURE_ADAPTER_INPUT",
		"__adapter",
	}

	err := filepath.WalkDir(transport, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		if strings.HasSuffix(path, ".py") {
			t.Errorf("Python file present on the Codex lifecycle transport path: %q; #65 forbids any Python on this path — delete it and regenerate", path)
		}
		if filepath.Base(path) == "pasture-lifecycle.py" {
			t.Errorf("the generated Python lifecycle adapter %q still exists; L3 must delete it", path)
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		lower := strings.ToLower(string(data))
		for _, token := range forbiddenTokens {
			if strings.Contains(lower, strings.ToLower(token)) {
				t.Errorf("Codex lifecycle transport file %q contains forbidden token %q (Python/caller-selected-operation residue)", path, token)
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk committed Codex lifecycle transport %q: %v", transport, err)
	}

	// The deleted adapter must be gone from disk entirely.
	adapter := filepath.Join(root, ".codex", "hooks", "pasture-lifecycle.py")
	if _, statErr := os.Stat(adapter); statErr == nil {
		t.Errorf("%q still exists; L3 must git rm the generated Python adapter", adapter)
	}

	// hooks.json (the transport entrypoint config) must also be Python-free.
	hooksJSON, err := os.ReadFile(filepath.Join(root, ".codex", "hooks.json"))
	if err != nil {
		t.Fatalf("read committed hooks.json: %v", err)
	}
	for _, token := range forbiddenTokens {
		if strings.Contains(strings.ToLower(string(hooksJSON)), strings.ToLower(token)) {
			t.Errorf("committed .codex/hooks.json contains forbidden token %q", token)
		}
	}
}

// TestCodexCommittedHooksPackageInventoryHasNoPythonAdapter proves the committed
// hooks package holds exactly the exec-only event runners and hooks.json — and
// no Python adapter file. Expected to FAIL until L3 deletes the adapter.
func TestCodexCommittedHooksPackageInventoryHasNoPythonAdapter(t *testing.T) {
	t.Parallel()
	root := testModuleRoot(t)

	var want []string
	want = append(want, ".codex/hooks.json")
	for _, event := range codexLifecycleEventNamesForTest() {
		want = append(want, ".codex/hooks/events/"+event+".sh")
	}
	sort.Strings(want)

	base := filepath.Join(root, ".codex")
	var got []string
	err := filepath.WalkDir(base, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		slash := filepath.ToSlash(rel)
		// Scope to the lifecycle transport package (hooks), excluding the
		// separate agents package and the codex.toml manifest.
		if slash == ".codex/hooks.json" || strings.HasPrefix(slash, ".codex/hooks/") {
			got = append(got, slash)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk committed .codex tree: %v", err)
	}
	sort.Strings(got)
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("committed Codex lifecycle transport inventory drifted; run make generate:\n--- got ---\n%s\n--- want ---\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

// TestCodexTransportRegenerationIsByteStable proves the transport renderers are
// pure: two independent renders are byte-identical, so `make generate` twice
// yields no second-run diff on this path.
func TestCodexTransportRegenerationIsByteStable(t *testing.T) {
	t.Parallel()
	names := codexLifecycleEventNamesForTest()
	firstConfig, err := renderCodexHooksConfig(names)
	if err != nil {
		t.Fatalf("first hooks config: %v", err)
	}
	secondConfig, err := renderCodexHooksConfig(names)
	if err != nil {
		t.Fatalf("second hooks config: %v", err)
	}
	if firstConfig != secondConfig {
		t.Fatal("renderCodexHooksConfig is not byte-stable across renders")
	}
	for _, event := range names {
		if renderCodexEventRunner(event) != renderCodexEventRunner(event) {
			t.Fatalf("renderCodexEventRunner(%s) is not byte-stable across renders", event)
		}
	}
}


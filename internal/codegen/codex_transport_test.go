// This file is the L2 golden/absence suite for the Python-free, exec-only Codex
// lifecycle transport (Phase 8 decision 2, #65). It proves both the renderer
// contract (in memory) and the committed generated artifacts on disk. The
// on-disk assertions are expected to FAIL until L3 regenerates .codex/** and
// deletes the stale Python adapter — that failing state is the TDD specification
// L3 implements against.

// codexLifecycleTransportRoot is the committed generated lifecycle transport
// tree the audit scopes to. It deliberately excludes the agents package: only
// the hooks package carries the lifecycle transport.
const codexLifecycleTransportRoot = ".codex/hooks"

// expectedCodexRunner is the single source of truth for a runner's exact bytes
// in the tests, mirroring the production renderCodexEventRunner so a drift in
// either direction is caught.
func expectedCodexRunner(event string) string {
	return "#!/usr/bin/env sh\n" +
		"# Code generated by Pasture. DO NOT EDIT.\n" +
		"exec \"${PASTURE_BIN:-pasture}\" hook lifecycle" +
		" --harness codex --event " + event + " --host-version 0.146.0\n"
}

// TestCodexRunnerIsExecOnly proves each generated runner is a three-line,
// exec-only shim: shebang, provenance comment, and a single exec of the built
// Pasture CLI. It carries no JSON handling, no branching, and no filesystem
// probing — the shim's only job is binary resolution plus exec, so exact stdin
// passes through by inheritance.
func TestCodexRunnerIsExecOnly(t *testing.T) {
	t.Parallel()
	for _, event := range codexLifecycleEventNamesForTest() {
		event := event
		t.Run(event, func(t *testing.T) {
			t.Parallel()
			runner := renderCodexEventRunner(event)

			if runner != expectedCodexRunner(event) {
				t.Fatalf("runner for %s is not the canonical exec-only shim:\n--- got ---\n%s\n--- want ---\n%s", event, runner, expectedCodexRunner(event))
			}

			lines := strings.Split(strings.TrimRight(runner, "\n"), "\n")
			if len(lines) != 3 {
				t.Fatalf("runner for %s has %d lines, want exactly 3 (shebang, comment, exec); a fourth line is branching/logic the transport must not carry:\n%s", event, len(lines), runner)
			}
			if lines[0] != "#!/usr/bin/env sh" {
				t.Errorf("runner for %s shebang = %q", event, lines[0])
			}
			if !strings.HasPrefix(lines[2], "exec \"${PASTURE_BIN:-pasture}\" hook lifecycle ") {
				t.Errorf("runner for %s does not exec the built CLI: %q", event, lines[2])
			}

			// No JSON handling, no branching, no transcript/dir probing, no
			// Python, no caller-selected operation env.
			for _, forbidden := range []string{
				"python", "python3", "pasture-lifecycle", "SCRIPT_DIR", "dirname",
				"PASTURE_ADAPTER", "if ", "case ", "cat ", "echo ", "printf", "jq", "grep", "read ",
			} {
				if strings.Contains(runner, forbidden) {
					t.Errorf("runner for %s contains forbidden non-exec token %q; the shim must be exec-only:\n%s", event, forbidden, runner)
				}
			}
		})
	}
}

// TestCodexRunnerExactPreToolUseAndSessionStartLines locks the two events that
// carry authentic-capture evidence to their exact production exec lines, so the
// only two events allowed activation proof can never silently change contract.
func TestCodexRunnerExactPreToolUseAndSessionStartLines(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		"PreToolUse":   "exec \"${PASTURE_BIN:-pasture}\" hook lifecycle --harness codex --event PreToolUse --host-version 0.146.0",
		"SessionStart": "exec \"${PASTURE_BIN:-pasture}\" hook lifecycle --harness codex --event SessionStart --host-version 0.146.0",
	}
	for event, wantExec := range cases {
		runner := renderCodexEventRunner(event)
		if !strings.Contains(runner, wantExec+"\n") {
			t.Errorf("runner for %s missing exact exec line %q:\n%s", event, wantExec, runner)
		}
	}
}

// TestCodexHooksJSONUsesPlainCommandStrings proves every hooks.json entry is a
// plain, variable-free command string (`sh .codex/hooks/events/<Event>.sh`).
// Codex 0.146.0 only authentically proves plain-command-string invocation;
// host-side ${VAR} expansion in command strings is unproven and must not appear.
func TestCodexHooksJSONUsesPlainCommandStrings(t *testing.T) {
	t.Parallel()
	wire, err := renderCodexHooksConfig(codexLifecycleEventNamesForTest())
	if err != nil {
		t.Fatalf("renderCodexHooksConfig: %v", err)
	}
	var config codexHooksConfig
	if err := json.Unmarshal([]byte(wire), &config); err != nil {
		t.Fatalf("decode hooks config: %v", err)
	}
	for _, event := range codexLifecycleEventNamesForTest() {
		groups := config.Hooks[event]
		if len(groups) != 1 || len(groups[0].Hooks) != 1 {
			t.Fatalf("event %s has %+v, want exactly one command hook", event, groups)
		}
		command := groups[0].Hooks[0].Command
		want := "sh .codex/hooks/events/" + event + ".sh"
		if command != want {
			t.Errorf("event %s command = %q, want plain string %q", event, command, want)
		}
		if strings.Contains(command, "${") || strings.Contains(command, "$(") {
			t.Errorf("event %s command %q relies on unproven host-side variable expansion", event, command)
		}
	}
}

// TestCodexCommittedRunnersAreExecOnly proves the runners committed to the
// repository are byte-identical to the canonical exec-only shims. Expected to
// FAIL until L3 regenerates .codex/hooks/events/*.sh from the new renderer.
func TestCodexCommittedRunnersAreExecOnly(t *testing.T) {
	t.Parallel()
	root := testModuleRoot(t)
	for _, event := range codexLifecycleEventNamesForTest() {
		path := filepath.Join(root, ".codex", "hooks", "events", event+".sh")
		got, err := os.ReadFile(path)
		if err != nil {
			t.Errorf("read committed runner %q: %v; run make generate and commit the regenerated transport", path, err)
			continue
		}
		if string(got) != expectedCodexRunner(event) {
			t.Errorf("committed runner %s has drifted from the exec-only shim; run make generate:\n--- committed ---\n%s\n--- want ---\n%s", event, got, expectedCodexRunner(event))
		}
	}
}


// row is one declared arm for a synthetic target file.
type row struct {
	ordinal int
	arm     string
}

// harnessFile renders a minimal target file with the two tables the generator
// reads, in the shape the real target files use.
func harnessFile(capture, production []row) string {
	var b strings.Builder
	b.WriteString("package activation\n\n")
	b.WriteString("var xCaptureProofs = [...]captureProofDeclaration{\n")
	for _, r := range capture {
		fmt.Fprintf(&b, "\t{ordinal: %d, arm: %q, event: 1, fixture: \"f\"},\n", r.ordinal, r.arm)
	}
	b.WriteString("}\n\nvar xProductionProofs = [...]productionProofDeclaration{\n")
	for _, r := range production {
		fmt.Fprintf(&b, "\t{ordinal: %d, arm: %q, event: 1, test: \"t\"},\n", r.ordinal, r.arm)
	}
	b.WriteString("}\n")
	return b.String()
}

// writeTree writes one synthetic target file per harness into a temp dir and
// returns the dir. A harness the caller does not supply gets one in-range arm
// of each kind, because a file with no arm of a kind is refused.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for _, harness := range proofgen.Harnesses {
		body, ok := files[harness.TargetFile]
		if !ok {
			filler := []row{{harness.Low, "Filler" + strings.ReplaceAll(harness.Label, " ", "")}}
			body = harnessFile(filler, filler)
		}
		require.NoError(t, os.WriteFile(filepath.Join(dir, harness.TargetFile), []byte(body), 0o600))
	}
	return dir
}

func TestGenerateEmitsOneConstantPerArmInsideItsHarnessRange(t *testing.T) {
	t.Parallel()
	dir := writeTree(t, map[string]string{
		"claude_targets.go":   harnessFile([]row{{1, "SessionStart"}, {2, "SessionEnd"}}, []row{{1, "SessionStart"}}),
		"codex_targets.go":    harnessFile([]row{{100, "CodexSessionStart"}}, []row{{100, "CodexSessionStart"}}),
		"opencode_targets.go": harnessFile([]row{{200, "OpenCodeSessionCreated"}}, []row{{200, "OpenCodeSessionCreated"}}),
	})
	files, err := proofgen.Generate(dir)
	require.NoError(t, err)
	require.Len(t, files, 3)
	claude := string(files["proofs_claude.gen.go"])
	requireConstant(t, claude, "CaptureProofSessionStart", "CaptureProof", 1)
	requireConstant(t, claude, "CaptureProofSessionEnd", "CaptureProof", 2)
	requireConstant(t, claude, "ProductionProofSessionStart", "ProductionProof", 1)
	require.Contains(t, claude, `{name: "SessionStart", proof: CaptureProofSessionStart}`)
	require.Contains(t, claude, "// Code generated by \"go generate\"; DO NOT EDIT.")
	codex := string(files["proofs_codex.gen.go"])
	requireConstant(t, codex, "CaptureProofCodexSessionStart", "CaptureProof", 100)
	openCode := string(files["proofs_opencode.gen.go"])
	requireConstant(t, openCode, "CaptureProofOpenCodeSessionCreated", "CaptureProof", 200)
	requireConstant(t, openCode, "ProductionProofOpenCodeSessionCreated", "ProductionProof", 200)

	again, err := proofgen.Generate(dir)
	require.NoError(t, err)
	require.Equal(t, files, again, "generation is deterministic")
}

func TestGenerateRefusesADuplicateOrdinalAcrossTwoHarnessFilesNamingBothArms(t *testing.T) {
	t.Parallel()
	dir := writeTree(t, map[string]string{
		"claude_targets.go": harnessFile([]row{{1, "SessionStart"}}, []row{{1, "SessionStart"}}),
		"codex_targets.go":  harnessFile([]row{{1, "CodexSessionStart"}}, []row{{100, "CodexSessionStart"}}),
	})
	// Two files cannot share an in-range ordinal because the ranges are
	// disjoint, so a cross-file duplicate is always also a range violation and
	// the range refusal fires first. The collision refusal is exercised inside
	// one file below.
	_, err := proofgen.Generate(dir)
	require.ErrorContains(t, err, `outside the Codex range 100-199`)

	dir = writeTree(t, map[string]string{
		"claude_targets.go": harnessFile([]row{{7, "PreCompact"}, {7, "PostCompact"}}, []row{{7, "PreCompact"}}),
	})
	_, err = proofgen.Generate(dir)
	require.ErrorContains(t, err, `capture proof ordinal 7 is declared twice`)
	require.ErrorContains(t, err, `arm "PreCompact" in claude_targets.go`)
	require.ErrorContains(t, err, `arm "PostCompact" in claude_targets.go`)

	// Production ordinals are a separate space: the same ordinal in the
	// capture table and the production table is not a collision.
	dir = writeTree(t, map[string]string{
		"claude_targets.go": harnessFile([]row{{7, "PreCompact"}}, []row{{7, "PreCompact"}}),
	})
	_, err = proofgen.Generate(dir)
	require.NoError(t, err)
}

func TestGenerateRefusesAnArmOutsideItsHarnessRangeNamingTheArm(t *testing.T) {
	t.Parallel()
	for name, tc := range map[string]struct {
		file string
		rows []row
		want string
	}{
		"codex-arm-with-a-claude-ordinal":      {"codex_targets.go", []row{{5, "CodexSessionStart"}}, `capture proof arm "CodexSessionStart" in codex_targets.go has ordinal 5 outside the Codex range 100-199`},
		"claude-arm-above-its-range":           {"claude_targets.go", []row{{100, "SessionStart"}}, `capture proof arm "SessionStart" in claude_targets.go has ordinal 100 outside the Claude Code range 1-99`},
		"opencode-arm-below-its-range":         {"opencode_targets.go", []row{{199, "OpenCodeSessionCreated"}}, `outside the OpenCode range 200-299`},
		"opencode-arm-above-its-range":         {"opencode_targets.go", []row{{300, "OpenCodeSessionCreated"}}, `outside the OpenCode range 200-299`},
		"ordinal-zero-is-the-invalid-zero-arm": {"claude_targets.go", []row{{0, "SessionStart"}}, `has ordinal 0, which is reserved for the invalid zero value`},
	} {
		name, tc := name, tc
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			dir := writeTree(t, map[string]string{tc.file: harnessFile(tc.rows, tc.rows)})
			_, err := proofgen.Generate(dir)
			require.ErrorContains(t, err, tc.want)
		})
	}
}


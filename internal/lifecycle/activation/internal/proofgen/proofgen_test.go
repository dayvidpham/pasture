func TestParseRefusesRowsTheGeneratorCannotRead(t *testing.T) {
	t.Parallel()
	for name, tc := range map[string]struct{ body, want string }{
		"ordinal-is-an-expression": {
			"package activation\nvar a = [...]captureProofDeclaration{{ordinal: 1 + 1, arm: \"X\"}}\nvar b = [...]productionProofDeclaration{}\n",
			"must be an integer literal"},
		"ordinal-is-a-named-constant": {
			"package activation\nvar a = [...]captureProofDeclaration{{ordinal: first, arm: \"X\"}}\nvar b = [...]productionProofDeclaration{}\n",
			"must be an integer literal"},
		"arm-is-not-a-string-literal": {
			"package activation\nvar a = [...]captureProofDeclaration{{ordinal: 1, arm: name}}\nvar b = [...]productionProofDeclaration{}\n",
			"must be a string literal"},
		"arm-is-not-an-exported-identifier": {
			"package activation\nvar a = [...]captureProofDeclaration{{ordinal: 1, arm: \"session start\"}}\nvar b = [...]productionProofDeclaration{}\n",
			"must be an exported Go identifier fragment"},
		"row-without-an-ordinal": {
			"package activation\nvar a = [...]captureProofDeclaration{{arm: \"X\"}}\nvar b = [...]productionProofDeclaration{}\n",
			"needs both an ordinal and an arm name"},
		"positional-row": {
			"package activation\nvar a = [...]captureProofDeclaration{{1, \"X\", 1, \"f\"}}\nvar b = [...]productionProofDeclaration{}\n",
			"must use keyed fields"},
		"missing-production-table": {
			"package activation\nvar a = [...]captureProofDeclaration{}\n",
			"declares no production proof table"},
		"missing-capture-table": {
			"package activation\nvar b = [...]productionProofDeclaration{}\n",
			"declares no capture proof table"},
		"two-capture-tables": {
			"package activation\nvar a = [...]captureProofDeclaration{}\nvar c = [...]captureProofDeclaration{}\nvar b = [...]productionProofDeclaration{}\n",
			"declares two capture proof tables"},
	} {
		name, tc := name, tc
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			path := filepath.Join(t.TempDir(), "claude_targets.go")
			require.NoError(t, os.WriteFile(path, []byte(tc.body), 0o600))
			_, err := proofgen.Parse(path)
			require.ErrorContains(t, err, tc.want)
		})
	}
}

// TestGenerateRefusesAHarnessFileWithNoArmOfAKind is the control against a
// silent empty generation: a file whose tables the walk cannot read, or that
// is empty, must stop generation instead of emitting empty proof files that
// every range assertion would pass over.
func TestGenerateRefusesAHarnessFileWithNoArmOfAKind(t *testing.T) {
	t.Parallel()
	for name, body := range map[string]string{
		"both-tables-empty":         harnessFile(nil, nil),
		"production-table-empty":    harnessFile([]row{{100, "CodexSessionStart"}}, nil),
		"capture-table-empty":       harnessFile(nil, []row{{100, "CodexSessionStart"}}),
		"tables-under-another-type": strings.ReplaceAll(strings.ReplaceAll(harnessFile([]row{{100, "CodexSessionStart"}}, []row{{100, "CodexSessionStart"}}), "captureProofDeclaration", "captureProofRow"), "productionProofDeclaration", "productionProofRow"),
	} {
		name, body := name, body
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			dir := writeTree(t, map[string]string{"codex_targets.go": body})
			_, err := proofgen.Generate(dir)
			require.Error(t, err)
			require.Regexp(t, `codex_targets.go declares no (capture|production) proof (arm at all|table)`, err.Error())
		})
	}
}

// TestCommittedProofFilesMatchTheGenerator is the in-package drift gate: the
// three committed generated files must equal a fresh generation from the
// committed target files, so a hand edit to either side turns RED here as
// well as in the repository-wide generate gate.
func TestCommittedProofFilesMatchTheGenerator(t *testing.T) {
	t.Parallel()
	dir := filepath.Join("..", "..")
	files, err := proofgen.Generate(dir)
	require.NoError(t, err)
	for _, harness := range proofgen.Harnesses {
		committed, err := os.ReadFile(filepath.Join(dir, harness.Output))
		require.NoError(t, err, "the committed %s must exist; run make generate", harness.Output)
		require.Equal(t, string(files[harness.Output]), string(committed),
			"%s drifted from the proof declaration tables in %s; run make generate and commit the result", harness.Output, harness.TargetFile)
	}
}

// TestHarnessRangesAreDisjointAndExcludeZero pins the partition the generator
// enforces: three ranges, no overlap, none containing the invalid zero.
func TestHarnessRangesAreDisjointAndExcludeZero(t *testing.T) {
	t.Parallel()
	require.Len(t, proofgen.Harnesses, 3)
	for i, a := range proofgen.Harnesses {
		require.Greater(t, a.Low, 0, "%s range must exclude ordinal 0", a.Label)
		require.LessOrEqual(t, a.Low, a.High)
		for _, b := range proofgen.Harnesses[i+1:] {
			require.True(t, a.High < b.Low || b.High < a.Low, "%s range %d-%d overlaps %s range %d-%d", a.Label, a.Low, a.High, b.Label, b.Low, b.High)
		}
	}
}

// requireConstant asserts one generated constant with its type and ordinal,
// tolerant of the column alignment gofmt applies inside a const block.
func requireConstant(t *testing.T, source, name, enum string, ordinal int) {
	t.Helper()
	pattern := regexp.MustCompile(`(?m)^\t` + regexp.QuoteMeta(name) + `\s+` + enum + ` = ` + fmt.Sprint(ordinal) + `$`)
	require.Regexp(t, pattern, source, "generated source must declare %s %s = %d", name, enum, ordinal)
}

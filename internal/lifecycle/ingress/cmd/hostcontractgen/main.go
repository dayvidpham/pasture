func blocking(v hostcontract.BlockingMode) string {
	return []string{"", "NonBlocking", "Blocking", "ConditionallyBlocking"}[int(v)]
}
func mutation(v hostcontract.MutationMode) string {
	return []string{"", "MutationNone", "MutationInput"}[int(v)]
}

// failureIdent renders one runtime.FailureMode arm as the qualified Go
// identifier the generated manifests refer to. There is exactly ONE FailureMode
// vocabulary in the tree (internal/runtime), so the generated registration data
// keeps the native behavior the pinned contract declared: no arm is folded into
// another on the way out.
//
// The switch is exhaustive over the six declared arms. An unknown value can
// only mean a new arm was added to internal/runtime without teaching this
// renderer, so generation stops here rather than writing a manifest that
// silently mislabels a native failure behavior.
func failureIdent(v pastureruntime.FailureMode) string {
	switch v {
	case pastureruntime.FailureReportAndContinue:
		return "pastureruntime.FailureReportAndContinue"
	case pastureruntime.FailureExitTwoBlocks:
		return "pastureruntime.FailureExitTwoBlocks"
	case pastureruntime.FailureStrictHook:
		return "pastureruntime.FailureStrictHook"
	case pastureruntime.FailureStrictExitTwoBlocks:
		return "pastureruntime.FailureStrictExitTwoBlocks"
	case pastureruntime.FailureThrowFailFast:
		return "pastureruntime.FailureThrowFailFast"
	case pastureruntime.FailureObserveOnly:
		return "pastureruntime.FailureObserveOnly"
	default:
		fatal(fmt.Errorf(
			"hostcontractgen: cannot render failure mode %d as a Go identifier, "+
				"because it is not one of the six arms of runtime.FailureMode; "+
				"this happened in failureIdent while rendering a registration manifest; "+
				"the manifest would otherwise label a native failure behavior wrongly, "+
				"and every generated adapter would inherit that label; "+
				"add the new arm to failureIdent in "+
				"internal/lifecycle/ingress/cmd/hostcontractgen/main.go",
			uint8(v)))
		return ""
	}
}
func stop(v hostcontract.StopLoopPolicy) string {
	return []string{"", "StopLoopNotApplicable", "StopLoopConsultWhenInactive"}[int(v)]
}
func binding(v model.NativeBindingKind) string {
	return map[model.NativeBindingKind]string{model.BindingSession: "model.BindingSession", model.BindingTurn: "model.BindingTurn", model.BindingRequest: "model.BindingRequest", model.BindingToolCall: "model.BindingToolCall", model.BindingAgent: "model.BindingAgent"}[v]
}
func fatal(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }

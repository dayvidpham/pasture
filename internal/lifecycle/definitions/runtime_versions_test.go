package definitions_test

import (
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"testing"

	"github.com/dayvidpham/pasture/internal/lifecycle/definitions"
	"github.com/dayvidpham/pasture/internal/lifecycle/model"
	"github.com/dayvidpham/pasture/internal/testutil"
	"github.com/stretchr/testify/require"
)

func TestReleasedRuntimeV1BodiesRetainTheirDecoderAndSemanticCoordinates(t *testing.T) {
	t.Parallel()
	var ledger struct {
		Versions []struct {
			Contract string `yaml:"contract"`
			Version  uint32 `yaml:"version"`
			SHA256   string `yaml:"sha256"`
		} `yaml:"versions"`
	}
	testutil.LoadFixtures(t, testutil.RuntimeDocumentVersions, &ledger)
	for i, contract := range definitions.RuntimeContracts() {
		t.Run(contract.String(), func(t *testing.T) {
			t.Parallel()
			// Exact released generated bytes from base 4bf5e91, not reconstructed
			// from today's owners. The retained ledger authenticates every body.
			body, err := os.ReadFile(fmt.Sprintf("testdata/runtime-v1/runtime-%d.json", i))
			require.NoError(t, err)
			doc, err := definitions.Decode(body)
			require.NoError(t, err)
			require.Equal(t, uint32(1), doc.Version())
			content := doc.Content()
			matched := false
			for _, entry := range ledger.Versions {
				if entry.Contract == contract.String() && entry.Version == 1 {
					require.Equal(t, entry.SHA256, hex.EncodeToString(content[:]))
					matched = true
				}
			}
			require.True(t, matched)
			historical, err := definitions.ParseRuntimeSpecification(body)
			require.NoError(t, err)
			active, err := definitions.NewRuntimeContract(contract)
			require.NoError(t, err)
			current, err := definitions.ParseRuntimeSpecification(active.Body())
			require.NoError(t, err)
			require.Equal(t, current.Contract, historical.Contract)
			require.Equal(t, current.Registration.Contract, historical.Registration.Contract)
			require.Equal(t, current.Lifecycle, historical.Lifecycle, "old semantic rows stay resolvable independently of new registration metadata")
			for _, event := range historical.Registration.Events {
				require.Equal(t, model.SessionTransitionNone, event.SessionTransition)
			}
			require.Equal(t, uint32(2), active.Version())
			compatible, err := definitions.CompatibleSourceInventoryUpdate(body, active)
			require.NoError(t, err)
			require.False(t, compatible, "runtime semantics cannot use source-inventory replacement")
			var altered map[string]any
			require.NoError(t, json.Unmarshal(body, &altered))
			altered["specification"].(map[string]any)["registration"].(map[string]any)["Events"].([]any)[0].(map[string]any)["SessionTransition"] = 3
			incompatible, err := json.Marshal(altered)
			require.NoError(t, err)
			_, err = definitions.Decode(incompatible)
			require.ErrorContains(t, err, `unknown field "SessionTransition"`)
		})
	}
}
